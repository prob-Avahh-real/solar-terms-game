export const TERM_DURATION = 300;
export const DAY_CYCLE_DURATION = 60;

export function lerp(a, b, t) {
  return a + (b - a) * Math.max(0, Math.min(1, t));
}

export function getCurrentTermData(elapsedGameTime) {
  const cycleTime = elapsedGameTime % (TERM_DURATION * 24);
  const termIndex = Math.floor(cycleTime / TERM_DURATION);
  const progress = (cycleTime % TERM_DURATION) / TERM_DURATION;
  const current = SOLAR_TERMS[termIndex];
  const next = SOLAR_TERMS[(termIndex + 1) % 24];
  const transitionStart = 0.8;
  let blend = 0;
  if (progress > transitionStart) {
    blend = (progress - transitionStart) / (1 - transitionStart);
  }
  return {
    current, next, progress, blend, termIndex,
    termName: current.name, termNameEn: current.nameEn,
    season: current.season, description: current.description,
    nextTermIn: Math.ceil((1 - progress) * TERM_DURATION)
  };
}

export function getDayCycle(elapsedGameTime) {
  return (elapsedGameTime % DAY_CYCLE_DURATION) / DAY_CYCLE_DURATION;
}

export function getSunPosition(dayCycle, termData) {
  const dayLength = termData?.dayLength || 0.5;
  const sunrise = (1 - dayLength) / 2;
  const sunset = 1 - sunrise;
  let sunAngle = -0.2;
  if (dayCycle >= sunrise && dayCycle <= sunset) {
    const dayProgress = (dayCycle - sunrise) / (sunset - sunrise);
    sunAngle = Math.sin(dayProgress * Math.PI) * Math.PI * 0.8;
  }
  return {
    azimuth: dayCycle * Math.PI * 2,
    altitude: sunAngle,
    intensity: Math.max(0, Math.sin(sunAngle))
  };
}
